export function filterBooks({ ageBand, virtue, trap } = {}) {
  return SHAPEREADS_BOOKS.filter((book) => {
    const matchesAge = !ageBand || book.ageBand === ageBand;
    const matchesVirtue = !virtue || book.primaryVirtue === virtue;
    const matchesTrap = !trap || book.modernTrapTargeted === trap;
    return matchesAge && matchesVirtue && matchesTrap;
  });
}
